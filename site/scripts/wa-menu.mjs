// Business Partner — the WhatsApp bot's service menu, generated from the site
// catalogue.
//
// The bot (n8n workflow "BP-WhatsApp-Main" → node "Build Menu Response") used
// to carry a hand-written snapshot of the catalogue. It drifted: 84 of the 140
// services the site sells were unreachable on WhatsApp, and a customer who
// asked for one of them was told the category had nothing else. A menu that is
// typed by hand will always drift, so it is generated here instead and the diff
// shows up in review whenever the catalogue moves.
//
//   node site/scripts/wa-menu.mjs           → writes n8n/wa-menu-data.js
//   node site/scripts/wa-menu.mjs --check   → exits 1 if the file is stale
//
// Paste the generated block into the n8n code node in place of the CATS/SVCS
// constants; nothing else in that node depends on the data's shape.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT = join(ROOT, "n8n", "wa-menu-data.js");

// Category order is a selling decision, not alphabetical: the doors customers
// arrive through come first. A category present in the catalogue but missing
// here still ships — appended at the end with a neutral icon — so a new
// category can never disappear from the menu.
const ORDER = [
  ["Company Formation", "تأسيس الشركات", "Company Formation", "🏢"],
  ["Foreign Investment", "الاستثمار الأجنبي", "Foreign Investment", "🌍"],
  ["Premium Residency", "الإقامة المميزة", "Premium Residency", "🪪"],
  ["Government Relations", "العلاقات الحكومية", "Government Relations", "🏛️"],
  ["HR Services", "الموارد البشرية", "HR Services", "👥"],
  ["Recruitment", "التوظيف والاستقدام", "Recruitment & Talent", "🧑‍💼"],
  ["Business Support", "دعم الأعمال", "Business Support", "📊"],
  ["Real Estate", "المكاتب ومساحات العمل", "Offices & Workspaces", "🏗️"],
  ["AI Automation", "الأتمتة والذكاء الاصطناعي", "AI & Automation", "🤖"],
];

const slugify = (s) => String(s).toLowerCase().trim().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

function build() {
  const raw = JSON.parse(readFileSync(join(ROOT, "site", "assets", "data", "catalog.json"), "utf8"));
  const services = Array.isArray(raw) ? raw : (raw.services || raw.items || []);

  const seen = new Map(ORDER.map((c) => [c[0], c]));
  const cats = [];
  const byCat = new Map();
  for (const [category, ar, en, icon] of ORDER) { cats.push([slugify(category), ar, en, icon]); byCat.set(slugify(category), []); }

  for (const s of services) {
    if (!s.code) continue;
    const category = s.category || "";
    const slug = slugify(category);
    if (!byCat.has(slug)) {
      // A category the catalogue grew after this file was written.
      cats.push([slug, s.categoryAr || category, category, "📁"]);
      byCat.set(slug, []);
      seen.set(category, true);
    }
    // The page slug the site publishes the service at — the bot links to it.
    const page = String(s.url || "").split("/").filter(Boolean).pop() || String(s.code).toLowerCase();
    byCat.get(slug).push([s.code, s.nameAr || s.nameEn || s.code, s.nameEn || s.nameAr || s.code, page]);
  }

  const cleanCats = cats.filter((c) => (byCat.get(c[0]) || []).length);
  const lines = [];
  lines.push("// GENERATED by site/scripts/wa-menu.mjs — do not edit by hand.");
  lines.push("// Source: site/assets/data/catalog.json · " + services.length + " services · " + cleanCats.length + " categories.");
  lines.push("const CATS = [");
  lines.push(cleanCats.map((c) => "  " + JSON.stringify(c)).join(",\n"));
  lines.push("];");
  lines.push("const SVCS = {");
  lines.push(cleanCats.map((c) => "  " + JSON.stringify(c[0]) + ": [\n" + byCat.get(c[0]).map((s) => "    " + JSON.stringify(s)).join(",\n") + "\n  ]").join(",\n"));
  lines.push("};");
  return lines.join("\n") + "\n";
}

const out = build();
const check = process.argv.includes("--check");
let current = "";
try { current = readFileSync(OUT, "utf8"); } catch {}
if (check) {
  if (current !== out) {
    console.error("WhatsApp menu data is stale — run: node site/scripts/wa-menu.mjs");
    process.exit(1);
  }
  console.log("WhatsApp menu data matches the catalogue.");
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, out);
  const n = (out.match(/^    \[/gm) || []).length;
  console.log(`WhatsApp menu data written — ${n} services in n8n/wa-menu-data.js`);
}
