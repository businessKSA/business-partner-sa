it("!inner keeps only rows whose related row exists; plain embed yields null for a missing parent", async () => {
  // The repo's storage-key lookup: version → parent document.
  const [org] = await post("organizations", { name_ar: "inner" });
  const [doc] = await post("documents", { organization_id: org.id, category: "cr", title: "t" });
  const key = uniq("key");
  await post("document_versions", { document_id: doc.id, version_no: 1, storage_key: key }, "return=minimal");
  const hit = await rest(`document_versions?storage_key=eq.${key}&select=storage_key,documents!inner(organization_id)&limit=1`);
  assert.deepEqual(hit, [{ storage_key: key, documents: { organization_id: org.id } }]);
  assert.deepEqual(await rest(`document_versions?storage_key=eq.${uniq("missing")}&select=storage_key,documents!inner(organization_id)&limit=1`), []);

  // A parent that is genuinely absent: tasks.request_id is nullable.
  const [req] = await post("requests", { ref: uniq("BP-R"), type: "CONSULTATION", title: "طلب" });
  const [linked] = await post("tasks", { organization_id: org.id, title: "مرتبطة", request_id: req.id });
  const [orphan] = await post("tasks", { organization_id: org.id, title: "يتيمة" });
  const inner = await rest(`tasks?organization_id=eq.${org.id}&select=id,requests!inner(ref,title)&order=created_at`);
  assert.deepEqual(inner, [{ id: linked.id, requests: { ref: req.ref, title: "طلب" } }], "orphan excluded by !inner");
  const left = await rest(`tasks?organization_id=eq.${org.id}&select=id,requests(ref)&order=created_at`);
  assert.deepEqual(left, [{ id: linked.id, requests: { ref: req.ref } }, { id: orphan.id, requests: null }]);

  // Many side of !inner: documents having at least one version.
  const [noVersions] = await post("documents", { organization_id: org.id, category: "id", title: "empty" });
  const docs = await rest(`documents?organization_id=eq.${org.id}&select=id,document_versions!inner(id)`);
  assert.deepEqual(docs.map((d) => d.id), [doc.id]);
  assert.ok(!docs.some((d) => d.id === noVersions.id));
});

