// ------------------------------------------------------------ PATCH/DELETE --
it("PATCH and DELETE with filters return the affected rows, or null under return=minimal", async () => {
  const [org] = await post("organizations", { name_ar: "تعديل" });
  await post("tasks", [
    { organization_id: org.id, title: "x", status: "open" },
    { organization_id: org.id, title: "y", status: "open" },
    { organization_id: org.id, title: "z", status: "done" },
  ], "return=minimal");

  const patched = await rest(`tasks?organization_id=eq.${org.id}&status=eq.open`, { method: "PATCH", body: { status: "blocked", assigned_to: "bp" } });
  assert.deepEqual(patched.map((r) => [r.title, r.status, r.assigned_to]).sort(), [["x", "blocked", "bp"], ["y", "blocked", "bp"]]);
  assert.equal(await rest(`tasks?organization_id=eq.${org.id}&title=eq.z`, { method: "PATCH", body: { status: "cancelled" }, prefer: "return=minimal" }), null);
  assert.deepEqual(await rest(`tasks?organization_id=eq.${org.id}&title=eq.z&select=status`), [{ status: "cancelled" }]);
  assert.deepEqual(await rest(`tasks?organization_id=eq.${org.id}`, { method: "PATCH", body: {} }), [], "empty patch touches nothing");

  const deleted = await rest(`tasks?organization_id=eq.${org.id}&status=eq.blocked`, { method: "DELETE" });
  assert.deepEqual(deleted.map((r) => r.title).sort(), ["x", "y"]);
  assert.deepEqual((await rest(`tasks?organization_id=eq.${org.id}&select=title`)).map((r) => r.title), ["z"]);
  assert.equal(await rest(`tasks?organization_id=eq.${org.id}`, { method: "DELETE", prefer: "return=minimal" }), null);
  assert.deepEqual(await rest(`tasks?organization_id=eq.${org.id}`), []);
});

