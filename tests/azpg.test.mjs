it("anything outside the grammar rejects loudly — never a silent full-table read", async () => {
  await assert.rejects(rest("tasks?status=foo.x"), /غير مدعوم/, "unknown operator");
  await assert.rejects(rest("tasks?status=open"), /غير مفهوم/, "filter without an operator");
  await assert.rejects(rest("tasks?status=is.maybe"), /غير مدعوم/, "is.<not null/true/false>");
  await assert.rejects(rest("users?select=id;drop"), /معرّف غير صالح/, "identifier with punctuation");
  // Values are parameters, never text: SQL inside a value is just an email
  // nobody has, so the query answers [] and the table is still there.
  assert.deepEqual(await rest(`users?select=id&email=eq.${encodeURIComponent('x"; drop table users;--')}`), []);
  await assert.rejects(rest("users?order=created_at desc"), /معرّف غير صالح/, "identifier in order");
  await assert.rejects(rest("nope_table?select=*"), (e) => /nope_table/.test(e.message), "unknown table");
  await assert.rejects(rest("tasks?select=id,nope(id)"), /غير موجود/, "unknown embed table");
  await assert.rejects(rest("tasks?or=(garbage)"), /or غير مفهوم/, "or with no column.op");
  await assert.rejects(rest("tasks?or=(status.bogus.x)"), /غير مدعوم/, "or part with an unknown operator");
  await assert.rejects(rest("tasks", { method: "PUT" }), /طريقة غير مدعومة/);
  await assert.rejects(post("tasks", [{}]), /بلا أعمدة/, "row with no columns");
  await assert.rejects(post("tasks", { organization_id: ORG.id, title: "t", nope: 1 }), (e) => /nope/.test(e.message), "unknown column on insert");
  // Sanity: the guard above ran against a table that does have rows.
  assert.ok((await rest("users?select=id&limit=1")).length === 1);
});

