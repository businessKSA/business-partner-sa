// api/_azpg.js against a REAL PostgreSQL, with db/schema.sql applied.
//
// WHY a live database and not a mock: the translator's whole job is to make
// Postgres answer exactly what PostgREST would have answered (timestamps as
// ISO strings, numerics as numbers, embeds as objects/arrays, defaults applied
// when a column is omitted). None of that can be asserted against a fake —
// the bugs it guards against were all "the SQL looked right" bugs.
//
// Runs only when a Postgres is reachable at AZPG_TEST_URL (default: the local
// bp_test database). Otherwise every test is SKIPPED, never failed — CI and
// other developers' machines may have no Postgres at all.
//
// Isolation: a throw-away schema `azpg_t_<hex>` is created, schema.sql is
// applied inside it, the translator is pointed at it through the URL's
// `options=-c search_path=…` (columnsOf() keys on current_schema()), and the
// schema is dropped at the end. The server's public schema is never touched.
import { test, before, after } from "node:test";
import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const TEST_URL = process.env.AZPG_TEST_URL || "postgres://bp_test:bp_test@127.0.0.1:5432/bp_test";
const SCHEMA = `azpg_t_${crypto.randomBytes(4).toString("hex")}`;
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// Probe first, synchronously for the test runner (top-level await), so the
// skip reason is known before any test is registered.
let pg = null, admin = null, unavailable = "";
try {
  pg = (await import("pg")).default;
  admin = new pg.Pool({ connectionString: TEST_URL, connectionTimeoutMillis: 1500, max: 1 });
  await admin.query("select 1");
} catch (e) {
  unavailable = `PostgreSQL not reachable at ${TEST_URL.replace(/\/\/[^@]*@/, "//…@")} (${e.code || e.message}) — set AZPG_TEST_URL`;
  try { await admin?.end(); } catch {}
  admin = null;
}
const it = (name, fn) => test(name, { skip: unavailable || false }, fn);

let azpg = null;   // the module under test, imported only after env is set
const rest = (p, o) => azpg.azpgRest(p, o);
const post = (table, body, prefer) => rest(table, { method: "POST", body, prefer });
const uuidRe = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const isoRe = /^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(\.\d+)?\+00:00$/;
const uniq = (p) => `${p}-${crypto.randomBytes(3).toString("hex")}`;

// Shared fixtures: one organization and one user; each test adds its own rows
// (keyed by unique values) so tests stay independent of each other's order.
let ORG = null, USER = null;

before(async () => {
  if (unavailable) return;
  const c = await admin.connect();
  try {
    await c.query(`create schema ${SCHEMA}`);
    await c.query(`set search_path to ${SCHEMA}`);
    // schema.sql is written for the Supabase SQL editor: one multi-statement
    // string (do $$ blocks, policies, an extension). pg runs it as a simple
    // query, which is exactly how the editor does it.
    await c.query(fs.readFileSync(path.join(ROOT, "db", "schema.sql"), "utf8"));
  } finally { c.release(); }

  process.env.AZURE_PG_URL = `${TEST_URL}${TEST_URL.includes("?") ? "&" : "?"}options=-c%20search_path%3D${SCHEMA}`;
  process.env.AZURE_PG_SSL = "0";          // local server has no TLS
  process.env.AZURE_PG_POOL_MAX = "2";
  azpg = await import(`../api/_azpg.js?t=${Date.now()}`);
  azpg.azpgForgetColumns();

  [ORG] = await post("organizations", { name_ar: "منشأة الاختبار", name_en: "Test Org", city: "الرياض" });
  [USER] = await post("users", { email: uniq("owner") + "@test.local", full_name: "Owner", locale: "ar" });
});

after(async () => {
  if (unavailable) return;
  try { if (azpg) await azpg.azpgClose(); } catch {}
  try { await admin.query(`drop schema ${SCHEMA} cascade`); } finally { await admin.end(); }
});

