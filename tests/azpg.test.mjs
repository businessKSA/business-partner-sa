  const [patched] = await rest(`requests?id=eq.${req.id}`, { method: "PATCH", body: { quote: { ...quote, status: "approved" }, scope: [{ code: "BP-CF-01", title: "تأسيس", qty: 1 }] } });
  assert.equal(patched.quote.status, "approved");
  assert.deepEqual(patched.scope, [{ code: "BP-CF-01", title: "تأسيس", qty: 1 }]);
  // A jsonb column set to a bare string must stay a JSON string, not become NULL/invalid.
  const [asText] = await rest(`requests?id=eq.${req.id}`, { method: "PATCH", body: { payment: "pending" } });
  assert.equal(asText.payment, "pending");

