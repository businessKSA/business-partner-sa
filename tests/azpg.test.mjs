it("POST applies DB defaults for omitted columns — even across rows with different column sets", async () => {
  // Regression: an earlier version sent an explicit NULL for every column any
  // row in the batch mentioned, which overrides `default now()` and breaks
  // `not null` on id/created_at. Rows must be grouped by their own columns.
  const rows = await post("organizations", [
    { name_ar: "أ" },
    { name_ar: "ب", city: "جدة", profile_completeness: 40 },
  ]);
  assert.equal(rows.length, 2);
  const a = rows.find((r) => r.name_ar === "أ"), b = rows.find((r) => r.name_ar === "ب");
  for (const r of [a, b]) {
    assert.match(r.id, uuidRe, "id generated by gen_random_uuid()");
    assert.match(r.created_at, isoRe, "created_at from default now()");
    assert.match(r.updated_at, isoRe);
  }
  assert.equal(a.city, null);
  assert.equal(a.profile_completeness, 0, "int default applied, as a number");
  assert.equal(b.city, "جدة");
  assert.equal(b.profile_completeness, 40);
  assert.equal(await post("organizations", [], "return=minimal"), null, "empty batch is a no-op");
});

