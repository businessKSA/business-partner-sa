// ----------------------------------------------------------------- FILTERS --
it("filters: eq/neq/in/not.in/is.null/not.is.null/gte/like/ilike/or", async () => {
  const [org] = await post("organizations", { name_ar: "مرشّحات" });
  const since = new Date(Date.now() - 60e3).toISOString();
  await post("tasks", [
    { organization_id: org.id, title: "فتح", status: "open", urgency: "urgent", details: "زيارة الرياض", due_at: new Date().toISOString() },
    { organization_id: org.id, title: "جارٍ", status: "in_progress", urgency: "soon", details: "Jeddah trip" },
    { organization_id: org.id, title: "منجزة", status: "done", urgency: "normal", details: "PAYID:ab_1 settled" },
    { organization_id: org.id, title: "ملغاة", status: "cancelled", urgency: "normal", details: "PAYID:abX1 other" },
  ], "return=minimal");
  const titles = async (q) => (await rest(`tasks?organization_id=eq.${org.id}&${q}&select=title&order=title`)).map((r) => r.title).sort();

  assert.deepEqual(await titles("status=eq.open"), ["فتح"]);
  assert.deepEqual(await titles("status=neq.open"), ["جارٍ", "ملغاة", "منجزة"]);
  assert.deepEqual(await titles("status=in.(open,in_progress,blocked)"), ["جارٍ", "فتح"]);
  assert.deepEqual(await titles('status=in.("open",done)'), ["فتح", "منجزة"], "quoted list values accepted");
  assert.deepEqual(await titles("status=not.in.(done,cancelled)"), ["جارٍ", "فتح"]);
  assert.deepEqual(await titles("status=in.()"), [], "empty list matches nothing");
  assert.deepEqual(await titles("due_at=is.null"), ["جارٍ", "ملغاة", "منجزة"]);
  assert.deepEqual(await titles("due_at=not.is.null"), ["فتح"]);
  assert.deepEqual(await titles("human_action=eq.false&urgency=in.(urgent,soon)"), ["جارٍ", "فتح"]);
  assert.deepEqual(await titles("human_action=is.false&urgency=eq.urgent"), ["فتح"]);
  assert.equal((await titles(`created_at=gte.${encodeURIComponent(since)}`)).length, 4, "gte on timestamptz with an ISO 'T' value");
  assert.deepEqual(await titles(`created_at=gte.${encodeURIComponent(new Date(Date.now() + 864e5).toISOString())}`), []);
  assert.deepEqual(await titles(`created_at=lt.${encodeURIComponent(since)}`), []);

  // Wildcards: * → %; a literal _ in the value must NOT act as a wildcard.
  assert.deepEqual(await titles("details=ilike.*رياض*"), ["فتح"]);
  assert.deepEqual(await titles("details=like.*jeddah*"), [], "like is case-sensitive");
  assert.deepEqual(await titles("details=ilike.*jeddah*"), ["جارٍ"]);
  assert.deepEqual(await titles("details=like.*PAYID:ab_1*"), ["منجزة"], "underscore escaped, so abX1 is not matched");
  assert.deepEqual(await titles("details=not.ilike.*PAYID*"), ["جارٍ", "فتح"]);

  // or=(…) as api/_simple.js builds it, with ilike parts and with eq parts.
  assert.deepEqual(await titles(`or=(title.ilike.*فتح*,details.ilike.*jeddah*)`), ["جارٍ", "فتح"]);
  assert.deepEqual(await titles(`or=(status.eq.done,status.eq.cancelled)&urgency=eq.normal`), ["ملغاة", "منجزة"], "or is AND-ed with sibling filters");
  assert.deepEqual(await titles(`or=(status.in.(open),due_at.is.null)`), ["جارٍ", "فتح", "ملغاة", "منجزة"], "nested parentheses inside or");
});

// ------------------------------------------------------------------- ORDER --
it("order/limit/offset, and NULL placement follows Postgres defaults unless nullslast/nullsfirst", async () => {
  const [org] = await post("organizations", { name_ar: "ترتيب" });
  const day = (n) => new Date(Date.UTC(2026, 0, n)).toISOString();
  // Separate POSTs so created_at differs (one statement → one now()).
  const [a] = await post("tasks", { organization_id: org.id, title: "a", due_at: day(3) });
  const [b] = await post("tasks", { organization_id: org.id, title: "b" });
  const [c] = await post("tasks", { organization_id: org.id, title: "c", due_at: day(1) });
  const ids = async (q) => (await rest(`tasks?organization_id=eq.${org.id}&${q}&select=id`)).map((r) => r.id);

  assert.deepEqual(await ids("order=created_at.desc"), [c.id, b.id, a.id]);
  assert.deepEqual(await ids("order=created_at"), [a.id, b.id, c.id], "bare column = asc");
  assert.deepEqual(await ids("order=created_at.asc&limit=2"), [a.id, b.id]);
  assert.deepEqual(await ids("order=created_at.asc&limit=2&offset=1"), [b.id, c.id]);
  assert.deepEqual(await ids("order=title.desc"), [c.id, b.id, a.id], "text ordering");
  assert.deepEqual(await ids("order=due_at"), [c.id, a.id, b.id], "asc → nulls last");
  assert.deepEqual(await ids("order=due_at.desc"), [b.id, a.id, c.id], "desc → nulls first (Postgres/PostgREST default)");
  assert.deepEqual(await ids("order=due_at.desc.nullslast"), [a.id, c.id, b.id]);
  assert.deepEqual(await ids("order=due_at.asc.nullsfirst"), [b.id, c.id, a.id]);
  assert.deepEqual(await ids("order=due_at.desc.nullslast,created_at.asc"), [a.id, c.id, b.id], "two keys");
});

