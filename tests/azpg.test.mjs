test("pgTextToIso normalises Postgres text timestamps to PostgREST's ISO form", async () => {
  // Pure function: runs even without a database.
  const { pgTextToIso } = await import(`../api/_azpg.js?t=${Date.now()}-unit`);
  assert.equal(pgTextToIso("2026-09-01 22:44:16.582+00"), "2026-09-01T22:44:16.582+00:00");
  assert.equal(pgTextToIso("2026-09-01 22:44:16+00"), "2026-09-01T22:44:16+00:00");
  assert.equal(pgTextToIso("2026-09-01 22:44:16.5+03:30"), "2026-09-01T22:44:16.5+03:30");
  assert.equal(pgTextToIso("2026-09-01 22:44:16"), "2026-09-01T22:44:16", "timestamp without time zone keeps no offset");
  assert.equal(pgTextToIso("2026-09-01"), "2026-09-01", "a date passes through");
  assert.equal(pgTextToIso("infinity"), "infinity", "unparseable text passes through untouched");
  assert.equal(pgTextToIso(null), null);
  assert.equal(pgTextToIso(undefined), undefined);
});

