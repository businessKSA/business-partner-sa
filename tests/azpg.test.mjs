it("the exact session lookup from api/_db.js: nested users object, expiry compared as time", async () => {
  const live = uniq("live"), dead = uniq("dead");
  await post("user_sessions", [
    { user_id: USER.id, organization_id: ORG.id, token_hash: live, expires_at: new Date(Date.now() + 3600e3).toISOString() },
    { user_id: USER.id, organization_id: ORG.id, token_hash: dead, expires_at: new Date(Date.now() - 3600e3).toISOString() },
  ], "return=minimal");

  // The ISO value carries a 'T'; Postgres' text form of the column carries a
  // space, and ' ' < 'T', so a text comparison would drop the live session.
  const q = (h) => `user_sessions?token_hash=eq.${h}&revoked_at=is.null&expires_at=gt.${encodeURIComponent(new Date().toISOString())}` +
    `&select=id,organization_id,expires_at,users(id,email,full_name,locale)&limit=1`;
  const rows = await rest(q(live));
  assert.equal(rows.length, 1);
  const s = rows[0];
  assert.deepEqual(Object.keys(s).sort(), ["expires_at", "id", "organization_id", "users"]);
  assert.equal(s.organization_id, ORG.id);
  assert.match(s.expires_at, isoRe);
  assert.ok(s.users && !Array.isArray(s.users), "to-one embed is an object, not an array");
  assert.deepEqual(s.users, { id: USER.id, email: USER.email, full_name: "Owner", locale: "ar" });

  assert.deepEqual(await rest(q(dead)), [], "expired session excluded");

  // Revoking hides it too (revoked_at=is.null).
  await rest(`user_sessions?token_hash=eq.${live}`, { method: "PATCH", body: { revoked_at: new Date().toISOString() }, prefer: "return=minimal" });
  assert.deepEqual(await rest(q(live)), []);
});

