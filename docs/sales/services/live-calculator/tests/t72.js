const {chromium}=require('playwright');
(async()=>{const b=await chromium.launch({executablePath:'/opt/pw-browsers/chromium-1194/chrome-linux/chrome'});
const p=await b.newPage({viewport:{width:1000,height:1400}});const errs=[];p.on('pageerror',e=>errs.push(e.message));
await p.goto('file://'+process.cwd()+'/index.html');await p.click('[data-tab=lump]');await p.waitForTimeout(300);
const opts=async(id)=>p.evaluate(id=>[...document.querySelectorAll('#'+id+' option')].map(o=>o.textContent).filter(Boolean).join(' | '),id);
console.log('lump term:',await opts('l-term'));
await p.click('[data-tab=cost]');await p.waitForTimeout(300);console.log('cost term:',await opts('c-term'));
await p.evaluate(()=>{const s=document.getElementById('c-term');s.value='u:day';s.dispatchEvent(new Event('change',{bubbles:true}));});await p.waitForTimeout(400);
console.log('picked day in cost ->',(await p.evaluate(()=>document.querySelector('#main').innerText)).slice(0,60).replace(/\n/g,' '),'| order view:',!!(await p.$('#o-add')));
console.log(errs);await b.close();})();
