// -----------------------------------------------------------------------
// تشغّل المتابعة الذكية مرة كل صباح: تفحص كل طلب مفتوح، وتفتح مهمة واحدة لكل
// مرحلة تجاوزت مهلتها، وترسل تذكيراً واحداً للعميل حين تكون الكرة عنده.
//
// لماذا هنا لا في Vercel Cron؟ الخطة الحالية (Hobby) تسمح بمهمتَي جدولة فقط
// وبمعدّل يومي، والمشروع يستهلكهما. n8n يشغّلها بلا هذا القيد.
//
// التوصيل:
//   Schedule Trigger (يومياً 09:00 بتوقيت الرياض) → هذه العقدة.
//   أضف BP_PANEL_KEY إلى متغيّرات n8n (نفس مفتاح لوحة /ops).
//
// العملية غير تراكمية بطبعها: مهمة مفتوحة من النوع نفسه تمنع فتح ثانية،
// وتذكير مسجّل داخل المهلة يمنع إرسال ثانٍ. تشغيلها مرتين لا يضاعف شيئاً،
// فتكرار الجدولة أو إعادة المحاولة بعد فشل شبكة آمنان.

const BASE = 'https://www.businesspartner.sa';
const KEY = $env.BP_PANEL_KEY || '';
if (!KEY) throw new Error('BP_PANEL_KEY غير مضبوط في متغيّرات n8n');

const r = await this.helpers.httpRequest({
  method: 'POST',
  url: `${BASE}/api/simple`,
  json: true,
  timeout: 60000,
  body: { action: 'ops-sweep', key: KEY, actor: 'المتابعة الذكية (n8n)' },
});

if (!r || !r.ok) throw new Error('فشلت المتابعة: ' + JSON.stringify(r).slice(0, 300));

// الأخطاء تُرفع لا تُبتلع: مسحٌ صامت لا يفعل شيئاً يبدو تماماً كمسحٍ لا شيء
// لديه ليفعله، وهكذا تتوقّف المتابعة عن مرحلة كاملة بلا أن ينتبه أحد.
if (r.errors && r.errors.length) {
  return [{ json: { ...r, alert: 'المتابعة عملت لكن بأخطاء', failed: r.errors.length } }];
}
return [{ json: r }];
