/**
 * يزرع بيانات العرض **مرّةً واحدة**، على قاعدةٍ لم تُزرع بعد.
 *
 * البذرة نفسها (`seed.ts`) تبدأ بـ`purgeTenantBySlug`: تمسح منشأة العرض
 * ثم تعيد بناءها. وهذا صحيحٌ في التطوير وكارثةٌ في النشر — فكل نشرةٍ
 * جديدة كانت ستمسح ما أدخله من يجرّب النظام، ويظنّه عطلاً في الحفظ.
 *
 * فالشرط هنا ليس «هل منشأة العرض موجودة؟» بل **«هل في القاعدة منشأةٌ
 * واحدة أصلاً؟»**: أوّل نشرةٍ تزرع، وكل ما بعدها يمرّ. وإن أنشأ المستخدم
 * منشأته الحقيقية ثم حذف منشأة العرض، لا تعود البذرة لتزرعها من خلفه.
 */
import { prisma, withoutTenant } from '../src/lib/db.ts';

async function main() {
  const count = await withoutTenant(
    'فحص ما إذا كانت القاعدة بكراً قبل زرع بيانات العرض',
    (tx) => tx.tenant.count(),
  );

  if (count > 0) {
    console.log(`↷ في القاعدة ${count} منشأة — تُترك كما هي ولا تُزرع.`);
    await prisma.$disconnect();
    return;
  }

  console.log('◇ القاعدة بكر — تُزرع بيانات العرض مرّةً واحدة.');
  await prisma.$disconnect();
  await import('./seed.ts');
}

main().catch((e) => {
  console.error('✗ فشل فحص البذر:', e);
  process.exit(1);
});
